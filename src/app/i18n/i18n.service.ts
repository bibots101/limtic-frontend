const DICT: Record<Langue, T> = { fr: FR, en: EN };

@Injectable({ providedIn: 'root' })
export class I18nService {
  langue = signal<Langue>('fr');

  constructor() {
    const saved = localStorage.getItem('limtic_langue') as Langue | null;
    if (saved === 'fr' || saved === 'en') this.langue.set(saved);
  }

  setLangue(l: Langue): void {
    this.langue.set(l);
    localStorage.setItem('limtic_langue', l);
  }

  t(cle: string): string {
    return DICT[this.langue()][cle] ?? DICT['fr'][cle] ?? cle;
  }
}
